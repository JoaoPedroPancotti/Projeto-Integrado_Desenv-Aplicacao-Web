-- 1. Departamentos da loja (ex: Hidráulica, Elétrica, Tintas)
CREATE TABLE IF NOT EXISTS categorias (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 2. Cadastro principal dos materiais de construção
CREATE TABLE IF NOT EXISTS produtos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Se a categoria for apagada, o produto fica sem categoria, mas não é deletado
    categoria_id INT REFERENCES categorias(id) ON DELETE SET NULL ON UPDATE CASCADE,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10,2),          -- preço de referência; entra sozinho nos novos pedidos
    unidade VARCHAR(20),          -- un, saco, m³, milheiro...
    imagem_url VARCHAR(500),
    ativo BOOLEAN NOT NULL DEFAULT true, -- desativado some do site
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 3. Quem pede orçamento pelo site (pedidos com o mesmo telefone ficam no mesmo cliente)
CREATE TABLE IF NOT EXISTS clientes (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150),
    telefone VARCHAR(20) NOT NULL,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 4. Cabeçalho do pedido de orçamento
CREATE TABLE IF NOT EXISTS orcamentos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Se o cliente for apagado (LGPD), seus orçamentos também são apagados
    cliente_id INT NOT NULL REFERENCES clientes(id) ON DELETE CASCADE ON UPDATE CASCADE,
    status VARCHAR(20) NOT NULL DEFAULT 'Pendente'
        CHECK (status IN ('Pendente', 'Em Andamento', 'Respondido', 'Aprovado', 'Concluído', 'Cancelado')),
    observacoes TEXT,             -- escrito pelo cliente no site
    valor_frete NUMERIC(10,2),
    desconto NUMERIC(10,2),
    forma_pagamento VARCHAR(40),
    resposta TEXT,                -- mensagem enviada ao cliente
    notas_internas TEXT,          -- só a loja vê
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 5. Produtos e quantidades de cada orçamento
CREATE TABLE IF NOT EXISTS itens_orcamento (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id INT NOT NULL REFERENCES orcamentos(id) ON DELETE CASCADE,
    -- Impede apagar um produto que já está salvo em algum orçamento
    produto_id INT NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    -- NUMERIC em vez de INT: material de construção é vendido em frações (2,5 m³ de areia)
    quantidade NUMERIC(10,3) NOT NULL,
    preco_unitario NUMERIC(10,2)
);

-- 6. Usuários do painel administrativo
CREATE TABLE IF NOT EXISTS administradores (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL, -- senha criptografada com bcrypt
    ativo BOOLEAN NOT NULL DEFAULT true,
    ultimo_acesso TIMESTAMPTZ,
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 7. Histórico de mudanças de cada orçamento
CREATE TABLE IF NOT EXISTS orcamento_historico (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orcamento_id INT NOT NULL REFERENCES orcamentos(id) ON DELETE CASCADE,
    administrador_id INT REFERENCES administradores(id) ON DELETE SET NULL,
    status VARCHAR(30) NOT NULL,
    descricao VARCHAR(255),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Índices nas chaves estrangeiras (o Postgres não cria sozinho)
CREATE INDEX IF NOT EXISTS idx_produtos_categoria ON produtos(categoria_id);
CREATE INDEX IF NOT EXISTS idx_orcamentos_cliente ON orcamentos(cliente_id);
CREATE INDEX IF NOT EXISTS idx_orcamentos_status ON orcamentos(status);
CREATE INDEX IF NOT EXISTS idx_itens_orcamento ON itens_orcamento(orcamento_id);
CREATE INDEX IF NOT EXISTS idx_itens_produto ON itens_orcamento(produto_id);
CREATE INDEX IF NOT EXISTS idx_historico_orcamento ON orcamento_historico(orcamento_id);

-- atualizado_em muda sozinho a cada UPDATE (no MySQL era o ON UPDATE CURRENT_TIMESTAMP)
CREATE OR REPLACE FUNCTION atualizar_data() RETURNS trigger AS $$
BEGIN
    NEW.atualizado_em = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS produtos_atualizado_em ON produtos;
CREATE TRIGGER produtos_atualizado_em BEFORE UPDATE ON produtos
    FOR EACH ROW EXECUTE FUNCTION atualizar_data();

DROP TRIGGER IF EXISTS orcamentos_atualizado_em ON orcamentos;
CREATE TRIGGER orcamentos_atualizado_em BEFORE UPDATE ON orcamentos
    FOR EACH ROW EXECUTE FUNCTION atualizar_data();

