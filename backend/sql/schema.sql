-- Código automático P00001, P00002... quando não for informado
CREATE OR REPLACE FUNCTION gerar_codigo_produto() RETURNS trigger AS $$
BEGIN
    IF NEW.codigo IS NULL OR btrim(NEW.codigo) = '' THEN
        NEW.codigo := 'P' || lpad(NEW.id::text, 5, '0');
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS produtos_codigo ON produtos;
CREATE TRIGGER produtos_codigo BEFORE INSERT OR UPDATE OF codigo ON produtos
    FOR EACH ROW EXECUTE FUNCTION gerar_codigo_produto();

UPDATE produtos SET codigo = 'P' || lpad(id::text, 5, '0') WHERE codigo IS NULL OR btrim(codigo) = '';
CREATE UNIQUE INDEX IF NOT EXISTS uq_produtos_codigo ON produtos(codigo);
CREATE UNIQUE INDEX IF NOT EXISTS uq_produtos_codigo_barras ON produtos(codigo_barras) WHERE codigo_barras IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_produtos_fornecedor ON produtos(fornecedor_id);

-- Baixa automática do estoque quando o pedido é concluído.
-- Na primeira vez, os pedidos que já estavam concluídos ficam fora do estoque (legado),
-- senão eles dariam baixa num estoque que ainda nem foi contado.
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = current_schema() AND table_name = 'orcamentos' AND column_name = 'estoque_baixado') THEN
        ALTER TABLE orcamentos ADD COLUMN estoque_baixado BOOLEAN NOT NULL DEFAULT false;
        ALTER TABLE orcamentos ADD COLUMN estoque_legado BOOLEAN NOT NULL DEFAULT false;
        ALTER TABLE orcamentos ADD COLUMN concluido_em TIMESTAMPTZ;
        UPDATE orcamentos SET estoque_legado = true, concluido_em = atualizado_em WHERE status = 'Concluído';
    END IF;
END $$;

-- 9. Kardex: toda entrada e saída de mercadoria, com o saldo antes e depois
CREATE TABLE IF NOT EXISTS movimentacoes_estoque (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Produto com movimentação não pode ser apagado (só desativado), para não perder o histórico
    produto_id INT NOT NULL REFERENCES produtos(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    tipo VARCHAR(20) NOT NULL
        CHECK (tipo IN ('entrada', 'devolucao', 'estorno', 'saida', 'perda', 'venda', 'ajuste', 'inventario')),
    quantidade NUMERIC(12,3) NOT NULL,      -- positivo entra, negativo sai
    saldo_anterior NUMERIC(12,3) NOT NULL,
    saldo_posterior NUMERIC(12,3) NOT NULL,
    custo_unitario NUMERIC(12,4),           -- custo da compra (entrada) ou custo médio na saída
    documento VARCHAR(60),                  -- nº da nota fiscal, romaneio...
    fornecedor_id INT REFERENCES fornecedores(id) ON DELETE SET NULL,
    orcamento_id INT REFERENCES orcamentos(id) ON DELETE SET NULL,
    administrador_id INT REFERENCES administradores(id) ON DELETE SET NULL,
    observacao VARCHAR(255),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_mov_produto ON movimentacoes_estoque(produto_id, criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_mov_data ON movimentacoes_estoque(criado_em DESC);
CREATE INDEX IF NOT EXISTS idx_mov_orcamento ON movimentacoes_estoque(orcamento_id);
CREATE INDEX IF NOT EXISTS idx_mov_fornecedor ON movimentacoes_estoque(fornecedor_id);

